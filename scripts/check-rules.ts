import fs from 'fs';
import path from 'path';

interface Violation {
  file: string;
  line: number;
  rule: string;
  match: string;
}

const violations: Violation[] = [];

// Directories to scan
const SCAN_DIRS = ['apps', 'packages', 'supabase', 'public'];
const SCAN_FILES: string[] = [];

// Extensions to scan
const SCAN_EXTENSIONS = ['.ts', '.tsx', '.css', '.html', '.sql', '.json', '.md'];

// Ignored files or patterns
const IGNORED_PATHS = [
  'node_modules',
  'dist',
  '.git',
  'package-lock.json',
  'check-rules.ts'
];

// Emoji regex
const EMOJI_REGEX = /[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{1F600}-\u{1F64F}\u{1F680}-\u{1F6FF}\u{1FA70}-\u{1FAFF}]/u;

// Em dash and En dash regex
const DASH_REGEX = /[\u2014\u2013]/;

function checkFile(filePath: string) {
  const relPath = path.relative(process.cwd(), filePath);
  if (IGNORED_PATHS.some(p => relPath.includes(p))) return;

  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  lines.forEach((line, idx) => {
    const lineNum = idx + 1;

    // 1. Check for Em Dash and En Dash
    if (DASH_REGEX.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned em dash / en dash (Use comma, colon, period, or "to")',
        match: line.trim()
      });
    }

    // 2. Check for Emojis
    if (EMOJI_REGEX.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned emoji character (Use Lucide SVG line icons)',
        match: line.trim()
      });
    }

    // 3. Check for Gradients
    if (/gradient/i.test(line) && !line.includes('check-rules.ts')) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned gradient (Flat design only: no gradients)',
        match: line.trim()
      });
    }

    // 4. Check for Pill-shaped buttons (border-radius: 999 / rounded-full)
    if (/border-radius:\s*(9999?px|50px)/i.test(line) && !line.includes('avatar') && !line.includes('awning')) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned pill radius (Buttons and chips must use 6px to 10px radius)',
        match: line.trim()
      });
    }

    // 5. Check for Lorem ipsum
    if (/lorem\s+ipsum/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned Lorem Ipsum placeholder text',
        match: line.trim()
      });
    }

    // 6. Check for IntersectionObserver (Scroll animation triggers)
    if (/IntersectionObserver/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned scroll-triggered animation (No IntersectionObserver)',
        match: line.trim()
      });
    }

    // 7. Check for Unsplash hotlinks
    if (/unsplash\.com/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned Unsplash hotlink (Use flat SVG category illustrations)',
        match: line.trim()
      });
    }

    // 8. Check for AI boilerplate
    if (/made with ai|generated by|vite \+ react/i.test(line)) {
      violations.push({
        file: relPath,
        line: lineNum,
        rule: 'Banned AI/template attribution tag',
        match: line.trim()
      });
    }
  });
}

function traverse(dir: string) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!IGNORED_PATHS.includes(entry.name)) {
        traverse(fullPath);
      }
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name);
      if (SCAN_EXTENSIONS.includes(ext)) {
        checkFile(fullPath);
      }
    }
  }
}

console.log('Running Design & Content Rules verification...');

for (const dir of SCAN_DIRS) {
  traverse(path.join(process.cwd(), dir));
}

for (const file of SCAN_FILES) {
  const fullPath = path.join(process.cwd(), file);
  if (fs.existsSync(fullPath)) {
    checkFile(fullPath);
  }
}

if (violations.length > 0) {
  console.error(`\nFound ${violations.length} design rule violation(s):\n`);
  violations.forEach(v => {
    console.error(`  [${v.rule}]`);
    console.error(`  --> ${v.file}:${v.line}`);
    console.error(`      "${v.match.substring(0, 100)}"\n`);
  });
  process.exit(1);
} else {
  console.log('All design, typography, and content rules passed with zero violations.');
  process.exit(0);
}
